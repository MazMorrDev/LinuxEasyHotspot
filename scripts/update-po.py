#!/usr/bin/env python3
"""Collects translatable strings into po/linuxeasyhotspot.pot and merges
them into every po/*.po (needs msgmerge from the gettext package).

    python3 scripts/update-po.py

UI strings are found in tr("…"), n_("…"), trf("…", …) and tr_n("…", "…", n)
calls; NetworkManager reasons and validation errors come from leh-model.
"""
import glob, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
S = r'"((?:[^"\\]|\\.)*)"'
CALL = re.compile(r'\b(?:tr|n_|trf)\(\s*' + S)
PLURAL = re.compile(r'\btr_n\(\s*' + S + r'\s*,\s*' + S)
MODEL = re.compile(r'(?:\be\(\s*(?:&format!\(\s*)?|#\[error\(\s*)' + S)

def strip_tests(src):
    i = src.find('#[cfg(test)]')
    return src if i < 0 else src[:i]

def line_of(src, pos):
    return src.count('\n', 0, pos) + 1

entries = {}  # msgid -> (plural or None, [refs])
def add(msgid, plural, ref):
    if not msgid:
        return
    e = entries.setdefault(msgid, [plural, []])
    e[1].append(ref)

for path in sorted(glob.glob(os.path.join(ROOT, 'crates/leh-gtk/src/**/*.rs'), recursive=True)):
    rel = os.path.relpath(path, ROOT)
    if rel.endswith('i18n.rs'):
        continue
    src = strip_tests(open(path, encoding='utf-8').read())
    for m in CALL.finditer(src):
        add(m.group(1), None, f'{rel}:{line_of(src, m.start())}')
    for m in PLURAL.finditer(src):
        add(m.group(1), m.group(2), f'{rel}:{line_of(src, m.start())}')

for name in ['reasons', 'password', 'ssid', 'config']:
    path = os.path.join(ROOT, f'crates/leh-model/src/{name}.rs')
    rel = os.path.relpath(path, ROOT)
    src = strip_tests(open(path, encoding='utf-8').read())
    for m in MODEL.finditer(src):
        s = m.group(1)
        if 'transparent' in s:
            continue
        # Run-time numbers are looked up as {n} (see i18n::tr_dyn).
        s = re.sub(r'\{[a-z0-9_]*\}', '{n}', s)
        if s.count('{n}') > 1:
            continue
        add(s, None, f'{rel}:{line_of(src, m.start())}')

def q(s):
    return '"' + s + '"'

out = ['# Translatable strings of LinuxEasyHotspot.',
       '# Generated by scripts/update-po.py; do not edit.',
       'msgid ""', 'msgstr ""',
       '"Content-Type: text/plain; charset=UTF-8\\n"',
       '"Plural-Forms: nplurals=2; plural=(n != 1);\\n"', '']
for msgid, (plural, refs) in entries.items():
    out.append('#: ' + ' '.join(refs[:4]))
    if '{' in msgid:
        out.append('#, no-c-format')
    out.append('msgid ' + q(msgid))
    if plural is not None:
        out += ['msgid_plural ' + q(plural), 'msgstr[0] ""', 'msgstr[1] ""']
    else:
        out.append('msgstr ""')
    out.append('')
pot = os.path.join(ROOT, 'po/linuxeasyhotspot.pot')
open(pot, 'w', encoding='utf-8').write('\n'.join(out))
print(f'{len(entries)} strings -> {os.path.relpath(pot, ROOT)}')

for po in sorted(glob.glob(os.path.join(ROOT, 'po/*.po'))):
    r = subprocess.run(['msgmerge', '--quiet', '--update', '--backup=none', '--no-wrap', po, pot])
    if r.returncode:
        sys.exit(r.returncode)
    print(f'merged {os.path.relpath(po, ROOT)}')
